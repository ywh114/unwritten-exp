def draw_text(rgb: np.ndarray, x: int, y: int, text: str,
              color: tuple[int, int, int], scale: int = 2) -> int:
    """Draw uppercase text at (x, y); returns the x after the last glyph."""
    for ch in text.upper():
        glyph = _FONT.get(ch, _FONT[" "])
        for row, bits in enumerate(glyph):
            for col in range(5):
                if bits >> (4 - col) & 1:
                    y0, y1 = y + row * scale, y + (row + 1) * scale
                    x0, x1 = x + col * scale, x + (col + 1) * scale
                    rgb[y0:y1, x0:x1] = color
        x += 6 * scale
    return x


def fill_rect(rgb: np.ndarray, x: int, y: int, w: int, h: int,
              color: tuple[int, int, int]) -> None:
    rgb[y:y + h, x:x + w] = color
